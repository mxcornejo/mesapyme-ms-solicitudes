-- Propietario: MP_SOL. No ejecutar en esquemas ajenos.

CREATE TABLE usuario (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  oidc_sub VARCHAR2(255 CHAR) NOT NULL UNIQUE,
  nombre VARCHAR2(150 CHAR) NOT NULL,
  rol VARCHAR2(15 CHAR) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL,
  CHECK (rol IN ('SOLICITANTE','TECNICO','ADMINISTRADOR')),
  CHECK (activo IN (0,1))
);

CREATE TABLE solicitud (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR2(150 CHAR) NOT NULL,
  descripcion VARCHAR2(2000 CHAR) NOT NULL,
  solicitante_id NUMBER NOT NULL REFERENCES usuario(id),
  tecnico_id NUMBER REFERENCES usuario(id),
  categoria_id NUMBER NOT NULL,
  categoria_nombre VARCHAR2(100 CHAR) NOT NULL,
  categoria_version NUMBER NOT NULL,
  prioridad VARCHAR2(10 CHAR) NOT NULL,
  impacto NUMBER(1) NOT NULL,
  urgencia NUMBER(1) NOT NULL,
  politica_id NUMBER NOT NULL,
  politica_version NUMBER NOT NULL,
  plazo_horas NUMBER(8,2) NOT NULL,
  estado VARCHAR2(25 CHAR) NOT NULL,
  creada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  vence_en TIMESTAMP WITH TIME ZONE NOT NULL,
  inicio_atencion_en TIMESTAMP WITH TIME ZONE,
  resuelta_en TIMESTAMP WITH TIME ZONE,
  cerrada_en TIMESTAMP WITH TIME ZONE,
  version NUMBER DEFAULT 1 NOT NULL,
  CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
  CHECK (estado IN ('NUEVA','ASIGNADA','EN_ATENCION','ESPERA_ANTECEDENTES','RESUELTA','CERRADA','CANCELADA')),
  CHECK (impacto BETWEEN 1 AND 3),
  CHECK (urgencia BETWEEN 1 AND 3),
  CHECK (plazo_horas > 0),
  CHECK (vence_en >= creada_en),
  CHECK (version >= 1)
);

CREATE TABLE historial (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id NUMBER NOT NULL REFERENCES solicitud(id),
  actor_id NUMBER REFERENCES usuario(id),
  tipo VARCHAR2(30 CHAR) NOT NULL,
  antes_json CLOB,
  despues_json CLOB,
  motivo VARCHAR2(2000 CHAR) NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (antes_json IS JSON),
  CHECK (despues_json IS JSON)
);

CREATE TABLE comentario (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id NUMBER NOT NULL REFERENCES solicitud(id),
  autor_id NUMBER NOT NULL REFERENCES usuario(id),
  texto VARCHAR2(2000 CHAR) NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE resolucion (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id NUMBER NOT NULL REFERENCES solicitud(id),
  tecnico_id NUMBER NOT NULL REFERENCES usuario(id),
  diagnostico VARCHAR2(2000 CHAR) NOT NULL,
  solucion VARCHAR2(2000 CHAR) NOT NULL,
  creada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE decision_solucion (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resolucion_id NUMBER NOT NULL UNIQUE REFERENCES resolucion(id),
  solicitante_id NUMBER NOT NULL REFERENCES usuario(id),
  decision VARCHAR2(10 CHAR) NOT NULL,
  motivo VARCHAR2(2000 CHAR),
  creada_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (decision IN ('CONFIRMAR','REABRIR')),
  CHECK (decision <> 'REABRIR' OR motivo IS NOT NULL)
);

CREATE TABLE outbox (
  event_id VARCHAR2(36 CHAR) PRIMARY KEY,
  solicitud_id NUMBER NOT NULL REFERENCES solicitud(id),
  aggregate_version NUMBER NOT NULL,
  tipo VARCHAR2(60 CHAR) NOT NULL,
  dedup_key VARCHAR2(150 CHAR) NOT NULL UNIQUE,
  payload CLOB NOT NULL,
  estado VARCHAR2(15 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
  intentos NUMBER DEFAULT 0 NOT NULL,
  disponible_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  publicado_en TIMESTAMP WITH TIME ZONE,
  ultimo_error VARCHAR2(1000 CHAR),
  CHECK (estado IN ('PENDIENTE','PUBLICADO','FALLIDO')),
  CHECK (payload IS JSON),
  CHECK (intentos >= 0)
);

CREATE INDEX ix_sol_due ON solicitud(estado, vence_en);
CREATE INDEX ix_sol_owner ON solicitud(solicitante_id, creada_en);
CREATE INDEX ix_sol_tech ON solicitud(tecnico_id, estado);
CREATE INDEX ix_hist_ticket ON historial(solicitud_id, creado_en);
CREATE INDEX ix_com_ticket ON comentario(solicitud_id, creado_en);
CREATE INDEX ix_res_ticket ON resolucion(solicitud_id, creada_en);
CREATE INDEX ix_outbox_retry ON outbox(estado, disponible_en);
